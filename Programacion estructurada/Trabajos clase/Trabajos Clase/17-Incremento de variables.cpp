#include <iostream>

using namespace std;

int main()
    {
    //declaracion de variables
        int x = 15;
        int y = -10;
        int z = 214;
    //proceso
        x=x+12;y=y+12;z=z+12;

    //impresion de resultados
        cout <<"Con el incremento la variable x es = " <<x <<"\n";
        cout <<"Con el incremento la variable y es = " <<y <<"\n";
        cout <<"Con el incremento la variable z es = " <<z <<"\n";
    return 0;
    }